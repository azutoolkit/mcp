import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const client = new Client({name:'azu-native-sdk-test',version:'1.0.0'});
const transport = new StdioClientTransport({command:process.argv[2],args:['serve','--config',process.argv[3]],stderr:'pipe'});
console.error("connecting");
await client.connect(transport); console.error("connected");
transport.stderr.on("data", d=>console.error(d.toString()));
console.error("tools");const tools = await client.listTools();
if (tools.tools.length < 30) throw Error('tool discovery failed');
console.error("call");const result = await client.callTool({name:'azu_toolkit_list',arguments:{workspace:process.argv[4]}});
if (result.isError || result.structuredContent.result.length !== 8) throw Error(JSON.stringify(result));
console.error("prompts");const prompts = await client.listPrompts();
await client.getPrompt({name:'review_upgrade',arguments:{workspace:process.argv[4]}});
console.error("resources");const resources = await client.listResources();
await client.readResource({uri:`azu://${process.argv[4]}/capabilities`});
console.error("parallel");const replies = await Promise.all(Array.from({length:6},()=>client.callTool({name:'azu_capabilities',arguments:{workspace:process.argv[4]}})));
if(replies.some(x=>x.isError)) throw Error('concurrency failed');
await client.close();
console.log(JSON.stringify({tools:tools.tools.length,prompts:prompts.prompts.length,resources:resources.resources.length,concurrent_requests:replies.length,result:'passed'}));
